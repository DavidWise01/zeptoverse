import assert from "node:assert/strict";
import {newFoam,balancedDigits,decodeDigits,redistribute,rotate,terminate,audit,verifyFoam} from "./nci-020-kernel.mjs";
for(let n=-400;n<=400;n++)assert.equal(decodeDigits(balancedDigits(n)),n);
assert.deepEqual(balancedDigits(0),[0]);
let s=newFoam({depth:3,root:"i",units:13});
const snapshot=JSON.stringify(s);
assert.equal(audit(s).totalCells,40);
assert.deepEqual(Object.values(audit(s).levels).map(x=>x.cells),[1,3,9,27]);
assert.equal(audit(s).allBalanced,true);
const parent="i",children=s.cells[parent].children;
const rotated=rotate(s,parent,1);
assert.equal(audit(rotated).allBalanced,true);
const unrolled=rotate(rotated,parent,-1);
assert.deepEqual(unrolled.order.map(id=>unrolled.cells[id].sign),s.order.map(id=>s.cells[id].sign));
const neg=children[0],pos=children[2];
let converted=redistribute(s,neg,pos);
assert.equal(converted.cells[neg].sign,0);
assert.equal(converted.cells[pos].sign,0);
converted=redistribute(converted,neg,pos);
assert.equal(converted.cells[neg].sign,-1);
assert.equal(converted.cells[pos].sign,1);
assert.equal(audit(converted).allBalanced,true);
const bad=redistribute(s,neg,"i/n/n");
assert.equal(bad.events.at(-1).type,"REJECT");
assert.equal(audit(bad).allBalanced,true);
const sealed=terminate(converted);
assert.equal(sealed.seal,"1/1 END END");
assert.equal(audit(sealed).rootUnits,13);
assert.equal(verifyFoam(sealed),true);
assert.equal(JSON.stringify(s),snapshot);
assert.deepEqual(terminate(redistribute(redistribute(newFoam({depth:3,root:"i",units:13}),neg,pos),neg,pos)),sealed);
assert.throws(()=>newFoam({depth:8}),/depth/);
console.log("NCI-020 PASS: signed ternary, nested generation, local balance, inverse operations, fixed source ancestry");
