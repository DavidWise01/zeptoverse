import assert from "node:assert/strict";
import {CANONICAL_GEOMETRY,coupledModes,rotate,audit} from "./nci-034-kernel.mjs";
const near=(a,b,r=1e-11)=>assert.ok(Math.abs(a-b)<=r*Math.max(Math.abs(a),Math.abs(b),1e-50),a+" != "+b);
const base=coupledModes();
assert.equal(base.geometry,"{brace/gyro[box(torroid)]}");
assert.deepEqual(base.frame.map(x=>x.sign),[-1,0,1]);
assert.equal(audit(base).valid,true);
const zero=coupledModes({coupling:0,anisotropy:0});
near(zero.eigenvaluesJ[0],Math.min(...zero.uncoupledEnergiesJ));
near(zero.eigenvaluesJ[1],Math.max(...zero.uncoupledEnergiesJ));
const rigid0=coupledModes({anisotropy:0,angleRad:0});
const rigid1=coupledModes({anisotropy:0,angleRad:Math.PI/3});
near(rigid0.eigenvaluesJ[0],rigid1.eigenvaluesJ[0]);
near(rigid0.eigenvaluesJ[1],rigid1.eigenvaluesJ[1]);
const a=coupledModes({anisotropy:.5,angleRad:0});
const b=coupledModes({anisotropy:.5,angleRad:Math.PI/2});
assert.ok(a.splittingJ>b.splittingJ);
const orbit=rotate({steps:24,anisotropy:.5});
assert.equal(orbit.points.length,25);
assert.ok(orbit.maxSplittingJ>orbit.minSplittingJ);
assert.equal(rotate({anisotropy:0}).orientationSensitive,false);
const finer=coupledModes({sideM:1e-22});
near(finer.eigenvaluesJ[0]/base.eigenvaluesJ[0],10);
near(finer.eigenvaluesJ[1]/base.eigenvaluesJ[1],10);
assert.throws(()=>coupledModes({coupling:.8,anisotropy:.5}),/unstable/);
assert.throws(()=>coupledModes({innerScale:0}),/invalid/);
assert.throws(()=>rotate({steps:1}),/gyro steps/);
assert.equal(audit(coupledModes({angleRad:3})).physicalEvidenceClaimed,false);
console.log("NCI-034 PASS nested geometry lock, two-mode spectral trace/determinant, rotation invariance without anisotropy, 1/L scaling");
