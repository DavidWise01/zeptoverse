import assert from "node:assert/strict";
import {validate,orient} from "./nci-013-kernel.mjs";
import {makeDemo,candidates,attempt,selectAndCapture,iterate} from "./nci-014-kernel.mjs";
let s=makeDemo();
assert.equal(Object.values((await import("./nci-013-kernel.mjs")).iceRule(s,s.active)).every(v=>v.valid),true);
const original=JSON.stringify(s);
assert.deepEqual(candidates(s,"A").map(x=>x.id),["B","C","D","E"]);
let denied=attempt(s,"A","B",{maxUnits:1});
assert.equal(denied.reason,"CAPACITY");assert.deepEqual(denied.state.active,s.active);
assert.equal(denied.state.events.at(-1).type,"REJECT");assert.equal(JSON.stringify(s),original);
const forbidden=attempt(s,"A","B",{label:"A"});
assert.equal(forbidden.reason,"LABEL_COLLISION");
let first=selectAndCapture(s,"A");
assert.equal(first.accepted,true);assert.deepEqual(first.state.nodes[first.label].roots,["A","B"]);
assert.equal(first.state.nodes[first.label].units,2);
assert.equal(validate(first.state),true);
const run=iterate(s,"A",{maxSteps:4});
assert.equal(run.stop,"SINGLE_COMPOSITE");assert.equal(run.steps,4);
assert.deepEqual(new Set(run.state.nodes[run.anchor].roots),new Set(["A","B","C","D","E"]));
assert.equal(run.state.nodes[run.anchor].units,5);
assert.equal(JSON.stringify(s),original);
const replay=iterate(makeDemo(),"A",{maxSteps:4});
assert.deepEqual(replay,run);
const blocked=iterate(s,"A",{maxUnits:1,maxSteps:4});
assert.equal(blocked.steps,0);assert.equal(blocked.stop,"NO_LEGAL_CAPTURE");
assert.ok(blocked.state.events.some(e=>e.type==="REJECT"));
const noLegal=orient(s,"B","A");
assert.equal(attempt(noLegal,"A","B").reason,"ICE_RULE");
const oneStep=iterate(s,"A",{maxSteps:1});
assert.equal(oneStep.stop,"STEP_LIMIT");
console.log("NCI-014: deterministic selection, conserved capture, ice-rule denial, and immutable rejections passed");
