import assert from "node:assert/strict";
import {FRAME,spectrum,compare,scaleTest,audit} from "./nci-033-kernel.mjs";
const b=spectrum(),t=spectrum({geometry:"PERIODIC_T3"});
assert.deepEqual(FRAME.map(x=>x.sign),[-1,0,1]);
assert.equal(b.zeroMode,null);
assert.equal(b.excitedModeCount,27);
assert.deepEqual(b.fundamental.indices,[1,1,1]);
assert.equal(b.shells[0].degeneracy,1);
assert.equal(t.excitedModeCount,342);
assert.equal(t.zeroMode.indices.join(","),"0,0,0");
assert.equal(t.fundamental.n2,1);
assert.equal(t.shells[0].degeneracy,6);
assert.equal(t.shells.reduce((s,x)=>s+x.degeneracy,0),342);
const c=compare();
assert.ok(Math.abs(c.lowestEnergyRatioTorusToBox-2/Math.sqrt(3))<1e-12);
assert.equal(c.physicalCasimirEnergyClaimed,false);
assert.equal(audit({sideM:1e-21,maxIndex:3}).valid,true);
assert.equal(scaleTest().passed,true);
assert.equal(spectrum({geometry:"DIRICHLET_BOX",maxIndex:1}).excitedModeCount,1);
assert.equal(spectrum({geometry:"PERIODIC_T3",maxIndex:1}).excitedModeCount,26);
assert.equal(spectrum({sideM:1e-21}).fundamental.oneQuantumEnergyJ>0,true);
assert.throws(()=>spectrum({maxIndex:0}),/cutoff/);
assert.throws(()=>spectrum({geometry:"UNKNOWN"}),/geometry/);
assert.deepEqual(compare(),compare());
console.log("NCI-033 PASS: Dirichlet box vs periodic T3 scalar spectra, zero mode, shell degeneracies and 1/L scaling");
