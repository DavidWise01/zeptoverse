import assert from "node:assert/strict";
import {genesis,select,microscopicSignature,validateWorld} from "./nci-017-kernel.mjs";
import {objectiveFor,score,trial,train,audit,demonstration} from "./nci-018-kernel.mjs";
const first=genesis(),before=JSON.stringify(first),objective=objectiveFor(first);
assert.notEqual(select(first).key,objective.target);
assert.equal(score(select(first).key,objective),-1);
const step1=trial(first,objective);
assert.equal(step1.attempted,true);assert.equal(step1.score,-1);assert.equal(step1.restored,true);
assert.equal(JSON.stringify(first),before);
assert.equal(microscopicSignature(step1.world.physical),first.origin);
assert.equal(select(step1.world).key,objective.target);
const step2=trial(step1.world,objective);
assert.equal(step2.score,1);
assert.equal(microscopicSignature(step2.world.physical),first.origin);
const run=train(first,objective,4);
assert.deepEqual(run.history.map(x=>x.score),[-1,1]);
assert.equal(run.improved,true);assert.equal(run.stop,"TARGET_REACHED");
assert.equal(run.world.policy.events.filter(e=>e.type==="GENERATION_EVALUATION").length,2);
assert.equal(audit(run.world).everyTrialRestored,true);
assert.equal(audit(run.world).physicalMatchesGenesis,true);
assert.equal(audit(run.world).iceRuleValid,true);
assert.equal(validateWorld(run.world),true);
assert.deepEqual(demonstration().run,run);
assert.deepEqual(train(first,objective,0).history,[]);
assert.throws(()=>train(first,objective,-1),/invalid generation budget/);
assert.throws(()=>score("x",{type:"OTHER"}),/unknown objective/);
assert.deepEqual(train(genesis(),objective,4),run);
console.log("NCI-018 PASS: -1 to +1 objective, same physical genesis, contiguous feedback ledger, deterministic replay");
