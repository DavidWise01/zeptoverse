import assert from "node:assert/strict";
import {genesis,witness,evidence,select,act,inverse,validateWorld,choices,microscopicSignature} from "./nci-017-kernel.mjs";
import {protonLedger} from "./nci-015-kernel.mjs";
const {plain,experienced,primary,second,samePhysics,differentChoice}=witness();
assert.equal(samePhysics,true);
assert.equal(differentChoice,true);
assert.equal(primary.failures,0);
assert.equal(choices(experienced).find(x=>x.key===primary.key).failures,1);
assert.equal(select(experienced).key,second.key);
assert.equal(microscopicSignature(plain.physical),microscopicSignature(experienced.physical));
assert.equal(JSON.stringify(plain.physical),JSON.stringify(experienced.physical));
assert.equal(experienced.policy.events.length,1);
assert.equal(validateWorld(experienced),true);
assert.throws(()=>evidence(plain,["A","A","B"],"failure","invalid"),/legal candidate/);
const before=JSON.stringify(experienced);
const selected=select(experienced);
const executed=act(experienced);
assert.equal(executed.accepted,true);
assert.equal(protonLedger(executed.world.physical).iceRule.valid,true);
assert.notEqual(microscopicSignature(executed.world.physical),microscopicSignature(experienced.physical));
const restored=inverse(executed.world,selected.path);
assert.equal(microscopicSignature(restored.physical),microscopicSignature(plain.physical));
assert.equal(restored.policy.events.length,3);
assert.equal(validateWorld(restored),true);
assert.equal(JSON.stringify(experienced),before);
assert.deepEqual(witness(),{plain,experienced,primary,second,samePhysics,differentChoice});
const damaged=JSON.parse(JSON.stringify(restored));damaged.policy.events[1].seq=9;
assert.throws(()=>validateWorld(damaged),/sequence broken/);
console.log("NCI-017 PASS: identical physics, different learned choice, conserved inverse and ledger");
