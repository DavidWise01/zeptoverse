import assert from "node:assert/strict";
import {begin,generateSigner,publicKeyJwk,register,signPacket,acquire,inspect,checkpoint,audit,syntheticDemo} from "./nci-028-kernel.mjs";
const key=await generateSigner();let s=begin(),baseline=JSON.stringify(s);
s=register(s,{sensorId:"A",rootId:"A-ROOT",publicJwk:await publicKeyJwk(key)});
const base={eventId:"EVENT-1",sensorId:"A",rootId:"A-ROOT",measurementId:"M-1",
 upstreamRoots:[],valueK:290,timestampMs:99000,nonce:"nonce-1"};
const packet=await signPacket(base,key.privateKey);
const good=await acquire(s,packet);
assert.equal(good.accepted,true);assert.equal(good.state.receipts.length,1);
assert.equal(JSON.stringify(begin()),baseline);
const replay=await acquire(good.state,packet);
assert.equal(replay.accepted,false);assert.match(replay.reason,/replayed/);
assert.equal(replay.state.receipts.length,1);
const tamper=await acquire(s,{...packet,valueK:320});
assert.equal(tamper.accepted,false);assert.match(tamper.reason,/signature/);
const notSame=await acquire(s,{...packet,rootId:"OTHER"});
assert.equal(notSame.accepted,false);assert.match(notSame.reason,/root mismatch/);
const key2=await generateSigner();
const forged=await signPacket(base,key2.privateKey);
assert.equal((await acquire(s,forged)).accepted,false);
assert.equal(inspect(good.state,"EVENT-1").status,"COUNT_MISMATCH");
const demo=await syntheticDemo();
assert.equal(demo.gate.status,"CREDENTIAL_VERIFIED");
assert.equal(demo.gate.eligible,true);
assert.equal(demo.gate.physicallyIndependent,false);
assert.equal(demo.gate.seal,null);
assert.equal(audit(demo.state).physicalWitnessesAuthenticated,0);
assert.equal(demo.state.checkpoints.length,1);
assert.equal(audit(demo.state).receipts,3);
const checked=checkpoint(demo.state,"THERM-1");
assert.equal(checked.state.checkpoints[0].trustedPhysicalObservation,false);
assert.equal(checked.state.seal,null);
assert.equal((await syntheticDemo({shared:true})).gate.status,"SHARED_ROOT");
assert.equal((await syntheticDemo({disagree:true})).gate.status,"READING_DISAGREEMENT");
assert.equal((await syntheticDemo({skew:true})).gate.status,"CLOCK_DISAGREEMENT");
assert.equal((await syntheticDemo({tamper:true})).gate.status,"COUNT_MISMATCH");
const stale=await acquire(s,await signPacket({...base,timestampMs:1,nonce:"different"},key.privateKey));
assert.equal(stale.accepted,false);assert.match(stale.reason,/timestamp/);
const broken=JSON.parse(JSON.stringify(checked.state));broken.checkpoints[0].seal="1/1 END END";
assert.throws(()=>audit(broken),/unearned/);
console.log("NCI-028 PASS: P-256 signatures, pinned keys, tamper, replay, freshness, shared roots, no physical trust");
