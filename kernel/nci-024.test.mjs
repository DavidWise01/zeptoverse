import assert from "node:assert/strict";
import {initialize,choose,step,attempt,iterate,audit,demonstration} from "./nci-024-kernel.mjs";
const near=(a,b,tol=1e-10)=>assert.ok(Math.abs(a-b)<=tol*Math.max(1,Math.abs(a),Math.abs(b)),String(a)+" vs "+String(b));
const s=initialize(),before=JSON.stringify(s);
assert.deepEqual(choose(s),{mode:"PUMP",sign:-1,reason:"COLD_ABOVE_BAND"});
let pumped=step(s,1);
assert.equal(pumped.lastMode,"PUMP");
assert.ok(pumped.coldK<s.coldK&&pumped.hotK>s.hotK);
near(pumped.coldK,289.972);near(pumped.hotK,310.026);
near(pumped.electricalJ,997.6);
assert.ok(audit(pumped).entropyProducedJperK>0);
near(audit(pumped).energyResidualJ,0);
assert.equal(audit(pumped).triad.roots.length,3);
assert.equal(JSON.stringify(s),before);
const coast=initialize({coldK:289.7,targetColdK:289.9});
assert.equal(choose(coast).mode,"COAST");
const afterCoast=step(coast,1);
assert.ok(afterCoast.coldK>coast.coldK&&afterCoast.hotK<coast.hotK);
near(afterCoast.electricalJ,coast.electricalJ);
assert.ok(audit(afterCoast).entropyProducedJperK>0);
const stop=initialize({coldK:289.9,targetColdK:289.9});
assert.equal(choose(stop).mode,"STOP");
const afterStop=step(stop,1);
near(afterStop.coldK,stop.coldK);near(afterStop.hotK,stop.hotK);
near(audit(afterStop).entropyProducedJperK,0);
const noBudget=initialize({electricalJ:0});
assert.equal(choose(noBudget).reason,"NO_COOLING_OR_POWER");
const noHot=initialize({hotCeilingK:310});
assert.equal(choose(noHot).reason,"HOT_LIMIT");
const invalid=attempt(s,-1);
assert.equal(invalid.accepted,false);
assert.deepEqual(invalid.state.genesis,s.genesis);
assert.deepEqual(invalid.state.history.at(-1).type,"REJECT");
assert.equal(audit(invalid.state).valid,true);
const run=iterate(s,100,1);
assert.ok(run.steps>0&&run.steps<=100);
assert.equal(run.audit.valid,true);
assert.ok(run.audit.entropyProducedJperK>=0);
assert.deepEqual(demonstration(),demonstration());
assert.throws(()=>initialize({coldK:-1}),/temperatures/);
assert.throws(()=>step(s,6),/time step/);
const altered=JSON.parse(JSON.stringify(pumped));altered.coldK+=1;
assert.throws(()=>audit(altered),/energy conservation/);
console.log("NCI-024 PASS: finite heat capacities, pump/coast/stop, energy, entropy, rejection, replay");
