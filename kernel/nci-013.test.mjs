import assert from "node:assert/strict";
import {createKernel,pair,capture,divide,validate,replay,orient,iceRule,checkpoint} from "./nci-013-kernel.mjs";
const roots=["A","B","D"].map(id=>({id,units:1}));
let s=createKernel(roots);
s=pair(s,"A","B");s=capture(s,"A","B","AC");s=capture(s,"AC","D","ACD");
assert.deepEqual(s.nodes.ACD.roots,["A","B","D"]);
assert.equal(s.nodes.ACD.units,3);
assert.deepEqual(s.active,["ACD"]);
s=checkpoint(s,"terminal");
assert.equal(s.checkpoints[0].seal,"1/1 END END");
const branch=divide(s,"ACD",["A","B"],"AC2","D2");
assert.deepEqual(branch.active,["AC2","D2"]);
assert.equal(branch.nodes.AC2.units+branch.nodes.D2.units,3);
validate(branch);
assert.deepEqual(s.active,["ACD"]);
assert.throws(()=>capture(branch,"AC2","D2","AC2"));
assert.throws(()=>divide(branch,"AC2",["A","A"],"X","Y"));
const edges=[["O","N"],["O","E"],["O","S"],["O","W"]];
let lattice=createKernel(["O","N","E","S","W"].map(id=>({id,units:1})),edges);
for(const [from,to] of [["O","N"],["O","E"],["S","O"],["W","O"]])lattice=orient(lattice,from,to);
assert.equal(iceRule(lattice,["O"]).O.valid,true);
lattice=orient(lattice,"O","S");
assert.equal(iceRule(lattice,["O"]).O.valid,false);
assert.deepEqual(replay(roots,[],[["pair","A","B"],["capture","A","B","AC"],["capture","AC","D","ACD"],["checkpoint","terminal"]]),s);
console.log("NCI-013: all deterministic kernel assertions passed");
