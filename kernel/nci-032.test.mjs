import assert from "node:assert/strict";
import {PLANCK_M,CMB_K,frame,sample,sweep,scalingInvariant,audit} from "./nci-032-kernel.mjs";
const near=(a,b,rel=1e-8)=>assert.ok(Math.abs(a/b-1)<rel,String(a)+" vs "+String(b));
near(PLANCK_M,1.616255e-35,1e-5);
const f=frame();assert.deepEqual(f.states.map(x=>x.sign),[-1,0,1]);
assert.deepEqual(f.states.map(x=>x.role),["COSMIC_BACKGROUND","REFERENCE_SINGLET","POSITIVE_DEPARTURE"]);
assert.equal(f.states[0].kelvin,CMB_K);
const p=sample(1e-21);assert.ok(p.idealPressurePa<0&&p.idealEnergyJ<0);
assert.equal(p.interpretation,"BELOW_CONTINUUM_MATERIAL_VALIDITY");
assert.equal(p.physicalPredictionValidated,false);
const invariants=scalingInvariant(1e-18,1e-19);
assert.equal(invariants.passed,true);
near(invariants.pressureRatio,10000);
near(invariants.energyRatio,1000);
near(invariants.gravitationalRatio,100);
const record=sweep();
assert.equal(audit(record).valid,true);
assert.deepEqual(audit(record).ternaryRoles,{background:-1,reference:0,positiveDeparture:1});
assert.equal(record.points[0].gapM,1e-21);
assert.equal(record.points.at(-1).gapM,PLANCK_M);
assert.equal(record.points.at(-1).interpretation,"PLANCK_REGIME_EXTRAPOLATION");
assert.equal(audit(record).physicalEvidenceClaimed,false);
assert.throws(()=>sample(-1),/positive finite/);
assert.throws(()=>frame({departureK:0}),/invalid Kelvin frame/);
assert.throws(()=>sweep({steps:0}),/invalid scale sweep/);
assert.deepEqual(sweep(),sweep());
console.log("NCI-032 PASS: fixed cosmic ternary frame, inverse-power scaling, dimensionless gravity, Planck cutoff, model boundaries");
