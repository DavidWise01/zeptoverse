import assert from "node:assert/strict";
import {startTriad,diatomic,diodic,divisive,join,closeTriad,auditTriad,attemptDiodic,sampleRun} from "./nci-022-kernel.mjs";
import {idealCasimir} from "./nci-021-kernel.mjs";
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-30,"numbers disagree: "+a+" vs "+b);
const initial=startTriad(),before=JSON.stringify(initial);
assert.deepEqual(auditTriad(initial).ternary,{A:0,B:0,C:0});
let s=diatomic(initial,"A","B",50e-9,200e-9);
assert.deepEqual(auditTriad(s).ternary,{A:-1,B:1,C:0});
assert.equal(auditTriad(s).balanceError<1e-30,true);
assert.ok(idealCasimir(s.boundaries.A.gap,s.boundaries.A.area).force<0);
assert.ok(idealCasimir(s.boundaries.B.gap,s.boundaries.B.area).force<0);
const denied=attemptDiodic(s,"B","A",1e-20);
assert.equal(denied.accepted,false);
assert.equal(denied.state.events.at(-1).type,"REJECT");
assert.deepEqual(denied.state.boundaries,s.boundaries);
s=diodic(s,"A","B",1e-20);
assert.equal(s.boundaries.A.pockets.main,2e-20);
near(s.boundaries.B.pockets.main,1e-20);
s=divisive(s,"B","main",0.4,"left","right");
assert.equal(Object.keys(s.boundaries.B.pockets).length,2);
near(s.boundaries.B.pockets.left+s.boundaries.B.pockets.right,1e-20);
assert.equal(Object.keys(s.boundaries).length,3);
s=join(s,"B","left","right","main");
near(s.boundaries.B.pockets.main,1e-20);
s=diodic(s,"B","C",1e-20);
s=diodic(s,"C","A",1e-20);
s=diatomic(s,"A","B",100e-9,100e-9);
near(s.reservoir,0);
const final=closeTriad(s);
assert.equal(final.seal,"1/1 END END");
assert.equal(auditTriad(final).physicalRestored,true);
assert.deepEqual(auditTriad(final).ternary,{A:0,B:0,C:0});
assert.deepEqual(sampleRun(),final);
assert.deepEqual(sampleRun(),sampleRun());
assert.equal(JSON.stringify(initial),before);
assert.throws(()=>diodic(initial,"B","A",1e-20),/diode/);
assert.throws(()=>diatomic(initial,"A","A",1e-7,1e-7),/distinct/);
assert.throws(()=>divisive(initial,"A","main",1,"x","y"),/fraction/);
console.log("NCI-022 PASS: 3 physical Casimir boundaries, balanced work ledger, directed credits, split/join, closure");
