import assert from "node:assert/strict";
import {beginMemory,transition,reverseLast,settle,firstCycle,verifyMemory,fingerprint} from "./nci-016-kernel.mjs";
import {protonLedger} from "./nci-015-kernel.mjs";
const start=beginMemory(),unchanged=JSON.stringify(start);
const path=firstCycle(start);assert.ok(path&&path.length===3);
const moved=transition(start,path);
assert.equal(moved.history[0].status,"ACCEPT");
assert.notEqual(fingerprint(moved.state),start.genesis);
assert.equal(protonLedger(moved.state).iceRule.valid,true);
const restored=reverseLast(moved);
assert.equal(restored.history.length,2);
assert.equal(restored.history[1].status,"ACCEPT");
assert.equal(fingerprint(restored.state),start.genesis);
const seal=settle(restored);
assert.equal(seal.checkpoint.restored,true);
assert.equal(seal.history.at(-1).seal,"1/1 END END");
assert.equal(verifyMemory(seal),true);
assert.equal(JSON.stringify(start),unchanged);
const bad=transition(start,["A","B","A"]);
assert.equal(bad.history[0].status,"REJECT");
assert.equal(bad.history[0].before,bad.history[0].after);
assert.equal(bad.state.events.at(-1).type,"PROTON_REJECT");
assert.equal(verifyMemory(bad),true);
assert.equal(settle(moved).checkpoint.restored,false);
const damaged=JSON.parse(JSON.stringify(seal));
damaged.history[1].before="deadbeef";
assert.throws(()=>verifyMemory(damaged),/broken witness chain/);
const repeat=settle(reverseLast(transition(beginMemory(),path)));
assert.deepEqual(repeat,seal);
console.log("NCI-016: reversible cycle, preserved history, chain checks, immutable rejections PASS");
