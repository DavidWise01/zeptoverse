import assert from "node:assert/strict";
import {initialize} from "./nci-024-kernel.mjs";
import {begin,choose,observe,iterate,audit} from "./nci-025-kernel.mjs";
const near=(a,b,tol=1e-10)=>assert.ok(Math.abs(a-b)<tol*Math.max(1,Math.abs(a),Math.abs(b)),a+" != "+b);
const first=begin(),before=JSON.stringify(first);
assert.equal(choose(first).mode,"PUMP");
let a=observe(first);
assert.equal(a.history[0].requestedMode,"PUMP");
assert.equal(a.policy.samples.PUMP,1);
near(a.physical.coldK,289.972);
assert.equal(JSON.stringify(first),before);
assert.ok(audit(a).entropyNonnegative);
near(audit(a).physical.energyResidualJ,0);
const second=observe(a);
assert.equal(second.history[1].requestedMode,"PUMP");
assert.equal(second.history[1].trigger,"HYSTERESIS_HOLD");
assert.ok(Math.abs(second.history[1].errorK)<Math.abs(a.history[0].errorK));
const low=begin({physical:initialize({coldK:289.6,targetColdK:289.9})});
assert.equal(choose(low).mode,"COAST");
assert.ok(observe(low).physical.coldK>low.physical.coldK);
const stopped=begin({physical:initialize({coldK:289.9,targetColdK:289.9})});
assert.equal(choose(stopped).mode,"STOP");
near(observe(stopped).physical.coldK,stopped.physical.coldK);
const hot=begin({physical:initialize({hotCeilingK:310})});
assert.equal(choose(hot).mode,"STOP");
const empty=begin({physical:initialize({electricalJ:0})});
assert.equal(choose(empty).mode,"STOP");
const almostEmpty=begin({physical:initialize({electricalJ:.1})});
assert.equal(observe(almostEmpty).history[0].trigger,"INSUFFICIENT_ELECTRICAL_STORE");
assert.equal(observe(almostEmpty).history[0].requestedMode,"STOP");
const r=iterate(begin(),40,1);
assert.equal(r.generation,40);
assert.equal(audit(r).energyConserved,true);
assert.equal(audit(r).entropyNonnegative,true);
assert.equal(audit(r).physical.triad.roots.length,3);
assert.deepEqual(iterate(begin(),40),r);
assert.throws(()=>observe(begin(),-1),/integration step/);
assert.throws(()=>begin({learnRate:2}),/learning parameters/);
const broken=JSON.parse(JSON.stringify(second));broken.history[1].seq=4;
assert.throws(()=>audit(broken),/event gap/);
console.log("NCI-025 PASS: hysteresis hold, predictive slope refinement, finite heat, conservation, replay");
