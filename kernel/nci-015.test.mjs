import assert from "node:assert/strict";
import {demo, protonLedger, reverseBond, reverseCycle, findDirectedCycles, evolve} from "./nci-015-kernel.mjs";
import {capture} from "./nci-013-kernel.mjs";
const s=demo(),before=JSON.stringify(s),original=protonLedger(s);
assert.equal(original.iceRule.valid,true);
assert.equal(original.numberOfBondProtons,10);
assert.equal(original.siteCount,5);
assert.equal(original.protons.every(x=>x.donor!==x.acceptor),true);
const bond=original.protons[0],illegal=reverseBond(s,bond.donor,bond.acceptor);
assert.equal(illegal.accepted,false);
assert.equal(illegal.reason,"ICE_RULE_VIOLATION");
assert.equal(JSON.stringify(s),before);
assert.deepEqual(illegal.state.orientation,s.orientation);
assert.equal(illegal.state.events.at(-1).type,"PROTON_REJECT");
const cycles=findDirectedCycles(s);
assert.ok(cycles.length>0);
const rolled=reverseCycle(s,cycles[0]);
assert.equal(rolled.accepted,true);
assert.equal(protonLedger(rolled.state).iceRule.valid,true);
assert.equal(protonLedger(rolled.state).numberOfBondProtons,10);
assert.notDeepEqual(rolled.state.orientation,s.orientation);
assert.equal(reverseCycle(s,["A","B","C","D","E","A"]).accepted,false);
const reversed=reverseCycle(rolled.state,[...cycles[0]].reverse());
assert.equal(reversed.accepted,true);
assert.deepEqual(reversed.state.orientation,s.orientation);
const run=evolve(s,8);
assert.equal(run.accepted,8);
assert.equal(protonLedger(run.state).iceRule.valid,true);
assert.deepEqual(evolve(demo(),8),run);
let grouped=capture(s,"A","B","AB");
assert.equal(protonLedger(grouped).iceRule.valid,true);
assert.equal(protonLedger(grouped).numberOfBondProtons,10);
console.log("NCI-015: ice-rule conservation, directed loop moves, rejected flips, and replay PASS");
