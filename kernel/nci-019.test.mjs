import assert from "node:assert/strict";
import {genesis,evidence,select,microscopicSignature,choices} from "./nci-017-kernel.mjs";
import {findMapping,renameSurrogate,transfer,demonstrate,checkTransfer} from "./nci-019-kernel.mjs";
import {protonLedger} from "./nci-015-kernel.mjs";
const base=genesis(),first=select(base),trained=evidence(base,first.path,"failure","synthetic observation");
const renamed=renameSurrogate(base.physical,{A:"P",B:"Q",C:"R",D:"S",E:"T"});
assert.equal(protonLedger(renamed).iceRule.valid,true);
const target=genesis(renamed),before=JSON.stringify(target);
const mapping=findMapping(base.physical,renamed);
assert.ok(mapping);
const mapped=first.path.map(x=>mapping[x]);
const pivot=mapped.indexOf([...mapped].sort()[0]);
const mappedChoice=[...mapped.slice(pivot),...mapped.slice(0,pivot)].join(">");
assert.ok(choices(target).some(x=>x.key===mappedChoice));
const result=transfer(trained,target,{sourceId:"WITNESS-ONE"});
assert.equal(result.accepted,true);assert.equal(result.imported,1);
assert.equal(result.world.policy.events.length,1);
assert.equal(result.world.policy.events[0].independentWitness,false);
assert.equal(result.world.policy.events[0].evidenceRoot,"WITNESS-ONE#1");
assert.equal(choices(result.world).find(x=>x.key===mappedChoice).failures,1);
assert.notEqual(select(result.world).key,mappedChoice);
assert.equal(microscopicSignature(result.world.physical),target.origin);
assert.equal(JSON.stringify(target),before);
const again=transfer(trained,result.world,{sourceId:"WITNESS-ONE"});
assert.equal(again.imported,0);assert.equal(again.duplicates,1);
assert.equal(again.world.policy.events.length,1);
assert.equal(checkTransfer(again.world),true);
const other=renameSurrogate(base.physical,{A:"X",B:"Y",C:"Z",D:"U",E:"V"});
other.orientation[Object.keys(other.orientation)[0]].reverse();
assert.equal(findMapping(base.physical,other),null);
assert.equal(demonstrate().microstatePreserved,true);
assert.deepEqual(demonstrate(),demonstrate());
console.log("NCI-019 PASS: directed isomorphism, mapped policy, ancestry dedupe, invalid topology refusal");
