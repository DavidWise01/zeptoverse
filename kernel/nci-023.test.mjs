import assert from "node:assert/strict";
import {rates,begin,tick,setDrive,pairCasimir,attemptTick,audit,demonstrate} from "./nci-023-kernel.mjs";
const near=(actual,expected,tol=1e-11)=>assert.ok(Math.abs(actual-expected)<=tol*Math.max(1,Math.abs(expected)),actual+" != "+expected);
const r=rates();
near(r.coldHeatW,2.8);near(r.hotHeatW,5.2);near(r.electricalW,2.4);
assert.ok(r.entropyWperK>0);
assert.ok(r.cop<r.carnot);
near(r.hotHeatW-r.coldHeatW,r.electricalW);
const initial=begin(),serialized=JSON.stringify(initial);
let s=tick(initial,1);
near(s.accounts.coldJ,-2.8);near(s.accounts.hotJ,5.2);near(s.accounts.electricalJ,-2.4);
near(audit(s).energyResidual,0);
near(audit(s).entropyProductionJperK,r.entropyWperK);
assert.equal(audit(s).casimirTriad.roots.length,3);
assert.equal(JSON.stringify(initial),serialized);
s=pairCasimir(s,"A","B",50e-9,200e-9);
assert.deepEqual(audit(s).casimirTriad.ternary,{A:-1,B:1,C:0});
assert.equal(audit(s).valid,true);
s=pairCasimir(s,"A","B",100e-9,100e-9);
assert.equal(audit(s).casimirTriad.physicalRestored,true);
near(audit(s).energyResidual,0);
const reversed=attemptTick(initial,-1);
assert.equal(reversed.accepted,false);
assert.equal(reversed.state.events.at(-1).type,"REJECT");
assert.deepEqual(reversed.state.accounts,initial.accounts);
assert.throws(()=>rates({coldK:-1}),/temperatures/);
assert.throws(()=>rates({hotK:250,coldK:290}),/temperatures/);
assert.throws(()=>tick(initial,0),/time step/);
const off=rates({currentA:0});
near(off.coldHeatW,-2);near(off.hotHeatW,-2);near(off.electricalW,0);
assert.ok(off.entropyWperK>0);
const stopped=tick(setDrive(initial,0),2);
assert.equal(audit(stopped).valid,true);
assert.ok(stopped.accounts.coldJ>0);
assert.deepEqual(demonstrate(),demonstrate());
const corrupt=JSON.parse(JSON.stringify(s));corrupt.accounts.hotJ+=1;
assert.throws(()=>audit(corrupt),/energy conservation/);
console.log("NCI-023 PASS: Peltier/Kelvin heat balance, Joule conduction, entropy, Carnot bound, Casimir coupling");
