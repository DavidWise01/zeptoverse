import assert from "node:assert/strict";
import {idealCasimir,start,signOfGap,move,attempt,close,audit} from "./nci-021-kernel.mjs";
const relative=(actual,expected,tol=1e-10)=>assert.ok(Math.abs(actual-expected)<=tol*Math.max(Math.abs(expected),1e-40));
const p=idealCasimir(1e-6,1e-12);
relative(p.pressure,-0.0013001257733831869,1e-4);
assert.ok(p.force<0&&p.energy<0);
const tiny=idealCasimir(100e-9,1e-12);
relative(tiny.pressure/p.pressure,1e4);
assert.equal(signOfGap(1e-7,1e-7),0);
assert.equal(signOfGap(0.5e-7,1e-7),-1);
assert.equal(signOfGap(1.5e-7,1e-7),1);
const initial=start(),serialized=JSON.stringify(initial);
const compressed=move(initial,50e-9);
assert.equal(compressed.ternary,-1);
assert.ok(compressed.model.pressure<0);
assert.equal(audit(compressed).valid,true);
const extended=move(initial,200e-9);
assert.equal(extended.ternary,1);
assert.ok(extended.model.pressure<0);
assert.ok(extended.model.pressure>initial.model.pressure);
assert.ok(extended.externalReservoir<0);
assert.ok(compressed.externalReservoir>0);
const returned=move(extended,100e-9);
assert.equal(returned.ternary,0);
relative(returned.externalReservoir,0,1e-10);
assert.equal(close(returned).seal,"1/1 END END");
assert.equal(close(extended).seal,null);
const rejected=attempt(initial,-1);
assert.equal(rejected.accepted,false);
assert.equal(rejected.state.gap,initial.gap);
assert.equal(rejected.state.history.at(-1).type,"REJECT");
assert.equal(JSON.stringify(initial),serialized);
assert.deepEqual(move(start(),200e-9),move(start(),200e-9));
assert.throws(()=>idealCasimir(0,1),/gap/);
console.log("NCI-021 PASS: inverse fourth-power pressure, attractive force, ±1 classification, conserved displacement ledger, closure and rejection");
