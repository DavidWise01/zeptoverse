import assert from "node:assert/strict";
import {begin,cycle,iterate,audit,agreement,reconstructCold} from "./nci-026-kernel.mjs";
const s=begin(),serialized=JSON.stringify(s);
const x=cycle(s,1);
assert.equal(x.packets.length,3);
assert.equal(x.gates[0].independentRoots,1);
assert.equal(x.gates[0].status,"SHARED_ANCESTRY");
assert.equal(x.gates[0].trusted,false);
assert.equal(x.gates[0].observationAgreement,true);
assert.equal(x.events[0].distinctAncestryRoots,1);
assert.equal(x.packets[2].method.includes("not prospective"),true);
assert.equal(JSON.stringify(s),serialized);
const before=x.packets.map(p=>p.observedK);
assert.deepEqual(before,[x.controller.physical.coldK,x.controller.physical.coldK,x.controller.physical.coldK]);
assert.ok(Math.abs(reconstructCold(s.controller.physical,x.controller.physical)-x.controller.physical.coldK)<1e-7);
assert.equal(audit(x).physical.entropyProducedJperK>=0,true);
const y=iterate(begin(),8);
assert.equal(y.generation,8);
assert.equal(audit(y).packets,24);
assert.equal(y.gates.every(g=>g.trusted===false&&g.independentRoots===1),true);
assert.deepEqual(iterate(begin(),8),y);
const duplicates=x.packets.map(p=>({...p}));
assert.equal(agreement(duplicates).status,"SHARED_ANCESTRY");
duplicates[1].observedK+=1;
assert.equal(agreement(duplicates).status,"DISAGREE");
const declared=x.packets.map((p,i)=>({...p,ancestryRoot:"EXTERNAL-DECLARED-"+i,predictedK:290}));
const hypothetical=agreement(declared);
assert.equal(hypothetical.status,"ELIGIBLE_NOT_VERIFIED");
assert.equal(hypothetical.trusted,false);
assert.throws(()=>agreement(x.packets.slice(1)),/three packets/);
assert.throws(()=>begin({toleranceK:-1}),/tolerances/);
console.log("NCI-026 PASS: three algorithms, common-source detection, observation mismatch and no false trust");
